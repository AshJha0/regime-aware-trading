#!/usr/bin/env python3
"""Net Sharpe and return against AUM for the bundled book.

Everything comes from `build_book` and the pinned gate, so the tool follows
whatever sizing the book uses.  Writes docs/CAPACITY_EVALUATION.md.

Run:  python tools/evaluate_capacity.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Callable, Dict, List, Optional

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "python" / "src"))

from evaluate_gate import build_gates, table  # noqa: E402
from regime import (  # noqa: E402
    CostAssumptions,
    GateBook,
    apply_gate,
    aum_at_sharpe_fraction,
    build_book,
    daily_cost_fraction,
    load_dataset,
    participation,
    sharpe,
)
from regime.costs import (  # noqa: E402
    ILLUSTRATIVE_FX_ADV_USD,
    ILLUSTRATIVE_FX_HALF_SPREAD_BPS,
    ILLUSTRATIVE_IMPACT_Y,
    ILLUSTRATIVE_TREND_ADV_USD,
    ILLUSTRATIVE_TREND_HALF_SPREAD_BPS,
)

AUM_GRID = (1e6, 3e6, 1e7, 3e7, 1e8, 3e8, 1e9, 3e9, 1e10)
LOW = AUM_GRID[0]
#: The halving search runs past the table so the unfiltered book gets a number.
HIGH = 1e11
Y_SCALES = (0.5, 1.0, 2.0)
ADV_SCALES = (0.1, 1.0, 10.0)
GATE_LABELS = {"unfiltered": "Unfiltered", "hmm": "HMM gate"}


def money(x: float) -> str:
    """Dollars in the shortest plain form."""
    if x >= 1e9:
        return f"${x / 1e9:.3g}bn"
    return f"${x / 1e6:.3g}m"


def book_weights(book: GateBook, gate: np.ndarray) -> np.ndarray:
    """Weights of the 50/50 book, trend then currency instruments."""
    return np.hstack([
        0.5 * apply_gate(book.momentum_positions, gate),
        0.5 * apply_gate(book.carry_positions, gate),
    ])


def illustrative_assumptions(book: GateBook, start: int, y_scale: float = 1.0, adv_scale: float = 1.0) -> CostAssumptions:
    """Illustrative spreads and ADV; sigma measured on the window."""
    n_trend = book.trend_returns.shape[1]
    n_fx = book.carry_returns.shape[1]
    returns = np.hstack([book.trend_returns, book.carry_returns])[start:]
    return CostAssumptions(
        half_spread_bps=np.r_[np.full(n_trend, ILLUSTRATIVE_TREND_HALF_SPREAD_BPS), np.full(n_fx, ILLUSTRATIVE_FX_HALF_SPREAD_BPS)],
        adv_usd=adv_scale * np.r_[np.full(n_trend, ILLUSTRATIVE_TREND_ADV_USD), np.full(n_fx, ILLUSTRATIVE_FX_ADV_USD)],
        sigma_daily=returns.std(axis=0, ddof=0),
        impact_y=y_scale * ILLUSTRATIVE_IMPACT_Y,
    )


def net_at(gross: np.ndarray, weights: np.ndarray, aum: float, costs: CostAssumptions, start: int) -> np.ndarray:
    """Daily net return on the window at one AUM."""
    return (gross - daily_cost_fraction(weights, aum, costs))[start:]


def sharpe_curve(gross: np.ndarray, weights: np.ndarray, costs: CostAssumptions, start: int) -> Callable[[float], float]:
    """Net Sharpe as a function of AUM."""
    return lambda aum: float(sharpe(net_at(gross, weights, aum, costs, start)))


def half_label(aum: Optional[float], base: float) -> str:
    """Text for a halving AUM, including the two cases with no number."""
    if base <= 0.0:
        return "undefined (Sharpe at $1m is not positive)"
    return f"above {money(HIGH)}" if aum is None else money(aum)


def render(book: GateBook, gates: Dict[str, np.ndarray], start: int) -> str:
    costs = illustrative_assumptions(book, start)
    n_trend = book.trend_returns.shape[1]
    out = [
        "# Capacity evaluation", "",
        "Generated by `python tools/evaluate_capacity.py`. Do not edit by hand; rerun the tool.", "",
        "**The book is synthetic, and ADV and spreads are assumptions.** The bundled instruments have no "
        "real volume or quotes, so every dollar figure below follows from the inputs listed here and says "
        "nothing about a real market. Read this page for the shape of the curve and how it moves with the "
        "inputs, not as a capacity estimate.", "",
        "## Model", "",
        "Cost per instrument per day, from `regime.costs`: "
        "`half_spread * |dw| * AUM + Y * sigma_daily * sqrt(|trade| / ADV) * |trade|`, with `trade = dw * AUM`. "
        "This is opt-in and separate from `run_backtest`, so no pinned number changes.", "",
    ]
    out += table(["Input", "Trend instruments", "Currency instruments", "Source class"], [
        ["Half spread", f"{ILLUSTRATIVE_TREND_HALF_SPREAD_BPS:g} bps", f"{ILLUSTRATIVE_FX_HALF_SPREAD_BPS:g} bps", "Illustrative, not calibrated"],
        ["ADV", money(ILLUSTRATIVE_TREND_ADV_USD), money(ILLUSTRATIVE_FX_ADV_USD), "Illustrative, not calibrated"],
        ["Y", f"{ILLUSTRATIVE_IMPACT_Y:g}", f"{ILLUSTRATIVE_IMPACT_Y:g}", "Illustrative, not calibrated"],
        ["Daily sigma (mean)", f"{costs.sigma_daily[:n_trend].mean():.2%}", f"{costs.sigma_daily[n_trend:].mean():.2%}", "Measured on the synthetic window"],
    ])
    out += [
        "",
        f"Window t >= {start}. AUM is fixed, and each day's trade fills in that day, so carry rebalances "
        "pay for one large print. The square-root form is a general rule of thumb. Where peak participation "
        "passes 100% of ADV the formula is outside anything it could describe, and those rows are a "
        "warning, not a forecast. The halving search runs to $100bn, past the table, so a halving figure "
        "above $10bn is an extrapolation of the formula and nothing more.", "",
    ]
    for key, label in GATE_LABELS.items():
        gate = gates[key]
        stream = book.stream(gate)
        weights = book_weights(book, gate)
        curve = sharpe_curve(stream.gross, weights, costs, start)
        half = half_label(aum_at_sharpe_fraction(curve, LOW, HIGH), curve(LOW))
        rows = []
        for aum in AUM_GRID:
            net = net_at(stream.gross, weights, aum, costs, start)
            cost = daily_cost_fraction(weights, aum, costs)[start:]
            rows.append([
                money(aum), f"{sharpe(net):.2f}", f"{252.0 * net.mean():.2%}", f"{252.0 * cost.mean():.2%}",
                f"{participation(weights, aum, costs)[start:].max():.2%}",
            ])
        out += [
            f"## {label}", "",
            f"Gross Sharpe {sharpe(stream.gross[start:]):.2f}, gross return {252.0 * stream.gross[start:].mean():.2%}, "
            f"turnover {252.0 * stream.turnover[start:].mean():.1f} per year.", "",
        ]
        out += table(["AUM", "Net Sharpe", "Net return", "Cost per year", "Peak participation"], rows)
        out += ["", f"Net Sharpe halves from its $1m value at: **{half}**.", ""]

    out += [
        "## Sensitivity", "",
        "AUM at which net Sharpe halves, with Y and ADV scaled around the illustrative values. "
        "The spread between cells shows how much of the answer is the assumption.", "",
    ]
    for key, label in GATE_LABELS.items():
        gate = gates[key]
        gross = book.stream(gate).gross
        weights = book_weights(book, gate)
        rows: List[List[str]] = []
        for y in Y_SCALES:
            row = [f"Y x {y:g}"]
            for adv in ADV_SCALES:
                curve = sharpe_curve(gross, weights, illustrative_assumptions(book, start, y, adv), start)
                row.append(half_label(aum_at_sharpe_fraction(curve, LOW, HIGH), curve(LOW)))
            rows.append(row)
        out += [f"### {label}", ""]
        out += table(["", *[f"ADV x {a:g}" for a in ADV_SCALES]], rows)
        out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "CAPACITY_EVALUATION.md")
    args = parser.parse_args()
    ds = load_dataset(ROOT / "data")
    gates, _, start = build_gates(ds)
    text = render(build_book(ds), gates, start)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
